







DROP TABLE IF EXISTS DA.PROJEKAT;

CREATE TABLE IF NOT EXISTS DA.PROJEKAT (
        INDEKS INTEGER NOT NULL,
        IDPREDMETA INTEGER NOT NULL,
        NAZIV       VARCHAR(20) NOT NULL,
        MAX_BROJ_POENA      INTEGER NOT NULL,
        OSVOJEN_BROJ_POENA  INTEGER,
        STATUS          VARCHAR(10),
        PRIMARY KEY(INDEKS, NAZIV, IDPREDMETA),
        FOREIGN KEY (INDEKS) REFERENCES DA.DOSIJE,
        FOREIGN KEY (IDPREDMETA) REFERENCES DA.PREDMET(ID),
        CONSTRAINT OGRANICENJE    CHECK(STATUS IN ('polozen', 'nepolozen'))
);




















